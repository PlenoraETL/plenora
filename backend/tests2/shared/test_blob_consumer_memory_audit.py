"""
Source-bound contract — bounded-read inventory ratchet for

object-storage blob consumers.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest


pytestmark = [pytest.mark.unit, pytest.mark.contract]


_BACKEND_ROOT = Path(__file__).resolve().parent.parent.parent
_APP = _BACKEND_ROOT / "app"


# Bounded-read inventory
#
# Each entry is keyed by (rel_path, lineno) of the b"".join(...) /
# list(...) callsite that consumes a get_object_stream body. The
# value is a tuple (risk, payload_class, user_controlled, cap_setting,
# rationale).
#
#   risk          - "HIGH" / "MEDIUM" / "LOW"
#   payload_class - free-text descriptor of expected size profile
#   user_controlled - bool: True if the upload size is set by an
#                     external user (vs system-generated)
#   cap_setting   - name of the settings key bounding the size, or
#                   "" if no cap applies
#   rationale     - human explanation (required, non-empty)

_BLOB_CONSUMER_INVENTORY: dict[tuple[str, int], tuple[
    str, str, bool, str, str,
]] = {
    # NOTE: The audit (TE-008) initially identified 4 callsites; the
    # following streams have closed the unbounded reads by replacing
    # `b"".join(stream["body"])` with bounded readers:
    #   - app/services/file_blob_materialization.py — closed by
    #     `_bounded_read_iterable(...)` (RESOURCE-ENGINE-011).
    #     The module is retired; the file_source read path now goes
    #     through `FileSourceBlobLoader`.
    #   - app/core/resources/loaders/result_blob.py — closed by
    #     `read_stream_bounded(...)` (RESOURCE-ENGINE-010).
    #   - app/core/intermediate/artifact_reader.py — closed by
    #     `read_stream_bounded(..., stage="intermediate_artifact_preview")`
    #     (RESOURCE-ENGINE-012). The HIGH entry was
    #     downgraded to LOW: the AST scan no longer matches the
    #     reader since the inline `b"".join(stream["body"])` is gone,
    #     so the entry is removed entirely (the ratchet's
    #     `stale - found` check would otherwise fail).
    # The remaining inline `b"".join(stream["body"])` callsite is
    # the IMDF plenora_metadata.json reader (LOW — bounded by IMDF
    # spec to a few KB).
    ("app/core/imdf/storage.py", 345): (
        "LOW",
        "IMDF plenora_metadata.json (small key/value pairs)",
        False,  # generated by IMDF persist pipeline; size determined
                # by IMDF spec (manifest-style)
        "",  # no cap; payload is structurally small
        "Meta-only JSON read; payloads are bounded by IMDF spec "
        "(few KB at most). No cap needed but worth a lightweight "
        "size-sanity log if size > 1MB. Worker 4 (IMDF) optional.",
    ),
}


# AST scan: find b"".join(<x>["body"]) and list(<x>["body"])


def _is_body_subscript(node: ast.AST) -> bool:
    """True if node is ``<expr>["body"]``."""
    return (
        isinstance(node, ast.Subscript)
        and isinstance(node.slice, ast.Constant)
        and node.slice.value == "body"
    )


def _scan_blob_consumer_callsites() -> dict[tuple[str, int], str]:
    """Find AST callsites of the form:
       - ``b"".join(<expr>["body"])``
       - ``list(<expr>["body"])``  (the list-then-join idiom)
       - ``b"".join(chunks)`` where ``chunks = list(<expr>["body"])``
         (multi-line variant; the join site is what we lock)

    Returns dict {(rel_path, lineno) -> shape_marker}.
    """
    found: dict[tuple[str, int], str] = {}

    for py in _APP.rglob("*.py"):
        if "__pycache__" in str(py):
            continue
        try:
            text = py.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        try:
            tree = ast.parse(text, filename=str(py))
        except SyntaxError:
            continue

        # Index every variable assigned from a list(<x>["body"]) call
        # so we can recognize a downstream ``b"".join(<that_var>)``.
        body_aliases: set[str] = set()
        for node in ast.walk(tree):
            if not isinstance(node, ast.Assign):
                continue
            v = node.value
            if (isinstance(v, ast.Call)
                    and isinstance(v.func, ast.Name) and v.func.id == "list"
                    and v.args and _is_body_subscript(v.args[0])):
                for tgt in node.targets:
                    if isinstance(tgt, ast.Name):
                        body_aliases.add(tgt.id)

        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            f = node.func
            # Pattern A: b"".join(<expr>["body"])
            if (isinstance(f, ast.Attribute) and f.attr == "join"
                    and isinstance(f.value, ast.Constant)
                    and f.value.value == b""
                    and node.args and _is_body_subscript(node.args[0])):
                rel = str(py.relative_to(_BACKEND_ROOT)).replace("\\", "/")
                found[(rel, node.lineno)] = "join_body_inline"
                continue
            # Pattern B: b"".join(<alias>) where alias was assigned
            # from list(<x>["body"]) earlier in the same module.
            if (isinstance(f, ast.Attribute) and f.attr == "join"
                    and isinstance(f.value, ast.Constant)
                    and f.value.value == b""
                    and node.args and isinstance(node.args[0], ast.Name)
                    and node.args[0].id in body_aliases):
                rel = str(py.relative_to(_BACKEND_ROOT)).replace("\\", "/")
                found[(rel, node.lineno)] = "join_body_via_alias"
                continue

    return found


# Tests


def test_blob_consumer_inventory_is_complete():
    """Ratchet: every production call site that consumes a
    ``get_object_stream`` body via ``b"".join(...)`` or via
    ``list(<stream>["body"])`` MUST appear in
    ``_BLOB_CONSUMER_INVENTORY`` with risk + rationale.

    A new bytes-accumulating site without an inventory entry
    fails this lock — the contributor must classify it as
    HIGH/MEDIUM/LOW with payload size profile + cap rationale.
    """
    found = _scan_blob_consumer_callsites()
    inventoried = set(_BLOB_CONSUMER_INVENTORY.keys())

    missing = set(found) - inventoried
    assert not missing, (
        "New blob-consumer call sites are not inventoried. Each "
        "MUST be classified explicitly:\n"
        + "\n".join(f"  {rel}:{ln} ({found[(rel, ln)]})" for rel, ln in sorted(missing))
        + "\nAdd to `_BLOB_CONSUMER_INVENTORY` with "
        "(risk, payload_class, user_controlled, cap_setting, "
        "rationale)."
    )

    stale = inventoried - set(found)
    assert not stale, (
        "Inventory contains entries that no longer exist in "
        "source (refactored away?). Trim them:\n"
        + "\n".join(f"  {rel}:{ln}" for rel, ln in sorted(stale))
    )


def test_blob_consumer_inventory_metadata_is_well_formed():
    """Every inventory entry MUST use a valid risk class, carry a
    non-trivial rationale (>= 60 chars), and respect the
    risk/cap correlation:
      - HIGH risk + no cap_setting -> rationale MUST mention
        Worker assignment ('Worker 2', 'Worker 3', 'Worker 4');
      - LOW risk MAY have no cap (rationale must justify why).
    """
    valid = {"HIGH", "MEDIUM", "LOW"}
    bad: list[str] = []
    for (rel, ln), (risk, payload_class, user_ctl, cap, rationale) in (
        _BLOB_CONSUMER_INVENTORY.items()
    ):
        loc = f"{rel}:{ln}"
        if risk not in valid:
            bad.append(f"{loc}: invalid risk {risk!r}")
            continue
        if not rationale or len(rationale.strip()) < 60:
            bad.append(
                f"{loc}: rationale too short ({len(rationale.strip())} chars; "
                f"need >= 60)"
            )
            continue
        if "TODO" in rationale:
            bad.append(f"{loc}: rationale contains TODO placeholder")
            continue
        if not payload_class.strip():
            bad.append(f"{loc}: payload_class is empty")
            continue
        if risk == "HIGH" and not cap.strip():
            # HIGH unbounded: must name the owner Worker so the
            # next stream picks it up.
            if not re.search(r"Worker\s*[234]", rationale):
                bad.append(
                    f"{loc}: HIGH-risk + no cap_setting requires "
                    f"a 'Worker 2/3/4' assignment in the rationale"
                )

    assert not bad, "Bad inventory metadata:\n" + "\n".join(f"  {b}" for b in bad)


def test_blob_consumer_high_risk_assignment_is_complete():
    """Lock the H-risk -> Worker assignment map.

    Audit-time TE-008 identified 3 HIGH-risk callsites; all 3 are
    now CLOSED in production by bounded readers
    (the legacy `file_blob_materialization` reader, retired in
    RESOURCE-ENGINE-024; `result_blob`; intermediate
    `artifact_reader`). HIGH-risk inventory is empty.

    Trim/extend in the same PR that closes the underlying issue.
    """
    high = sorted(
        rel_ln
        for rel_ln, (risk, *_rest) in _BLOB_CONSUMER_INVENTORY.items()
        if risk == "HIGH"
    )
    expected: list[tuple[str, int]] = []
    assert high == expected, (
        f"HIGH-risk inventory drift.\n"
        f"  expected: {expected}\n"
        f"  actual:   {high}\n"
        "If a HIGH-risk site has been bounded/migrated, downgrade "
        "the entry. If a new HIGH-risk site is identified, add it "
        "AND update this expected list."
    )
